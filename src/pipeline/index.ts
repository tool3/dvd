//#region High-Level Pipeline API

export interface RenderOptions {
  width: number;
  height: number;
  fontSize: number;
  theme: Theme;
  template?: 'macos' | 'windows' | 'minimal';
  title?: string;
  watermark?: string;
  embedFont?: boolean;
  fontData?: string;
  onFrame?: (frame: FrameData, index: number) => void;
  onProgress?: (current: number, total: number, description?: string) => void;
}

export const renderStatic = (input: string, options: RenderOptions): EmitResult => {
  const termWidth = Math.floor(options.width / (options.fontSize * 0.6));
  const termHeight = Math.floor(options.height / (options.fontSize * 1.4));
  let state = createGridState(termWidth, termHeight);

  state = processInput(state, input);

  const rows = coalesce(state, options.theme);

  return emit(
    rows,
    state.cursor,
    true,
    createEmitterOptions(options)
  );
};

export const renderAnimated = (
  frames: FrameData[],
  options: RenderOptions & { fps?: number; loop?: boolean; useFilmstrip?: boolean }
): EmitResult => {
  const emitterOptions = {
    ...createEmitterOptions(options),
    fps: options.fps,
    loop: options.loop,
  };

  // Use filmstrip (svg-term style) for better file size with truecolor content
  if (options.useFilmstrip) {
    return emitFilmstripAnimated(frames, emitterOptions);
  }

  return emitAnimated(frames, emitterOptions);
};


//#region Frame Capture

export interface CaptureOptions {
  width: number;
  height: number;
  fontSize: number;
  theme: Theme;
}

export const createFrameCapturer = (options: CaptureOptions) => {
  const termWidth = Math.floor(options.width / (options.fontSize * 0.6));
  const termHeight = Math.floor(options.height / (options.fontSize * 1.4));
  let state = createGridState(termWidth, termHeight);
  const frames: FrameData[] = [];
  const startTime = Date.now();

  return {
    getState(): GridState {
      return state;
    },

    write(input: string): void {
      state = processInput(state, input);
    },

    capture(cursorVisible: boolean = true): void {
      const rows = coalesce(state, options.theme);
      frames.push({
        rows,
        cursor: { ...state.cursor },
        cursorVisible,
        timestamp: Date.now() - startTime,
      });
    },

    getFrames(): FrameData[] {
      return frames;
    },

    reset(): void {
      state = createGridState(termWidth, termHeight);
      frames.length = 0;
    },
  };
};


//#region Typing Simulation

export interface TypeOptions {
  speed?: number;
  variance?: number;
}

export async function* simulateTyping(
  text: string,
  options: TypeOptions = {}
): AsyncGenerator<{ char: string; delay: number }> {
  const speed = options.speed ?? 50;
  const variance = options.variance ?? 20;

  for (const char of text) {
    const delay = speed + (Math.random() - 0.5) * variance * 2;
    yield { char, delay: Math.max(10, delay) };
  }
}


